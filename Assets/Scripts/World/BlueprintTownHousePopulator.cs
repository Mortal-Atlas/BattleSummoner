namespace BattleSummoner.World
{
    public enum BlueprintZoneType
    {
        OuterRing_ResidentialAndBazaar,
        MidRing_TerracedTownhomesAndShops,
        UpperRing_AcademyAndSanctuaryPerimeter
    }

    [Serializable]
    public struct TownBlueprintPlot
    {
        public string plotId;
        public BlueprintZoneType zoneTier;
        public Vector2 normalizedDiagramCoords; // Mapped directly from Antigravity's own diagram
        public float elevationHeightY;          // Stepped elevation increasing toward the center Church
        public float facingAngleDegrees;        // Oriented toward the wide mount-accessible street
        public bool isShopOrBakery;
    }

    /// <summary>
    /// Populates town houses, storefronts, artisan workshops, and bakeries across concentric
    /// elevation tiers according to Antigravity's self-generated blueprint and zoning diagram.
    /// Strictly preserves wide 14m-16m radial avenues at 0, 90, 180, and 270 degrees for mount squads.
    /// </summary>
    [ExecuteInEditMode]
    public class BlueprintTownHousePopulator : MonoBehaviour
    {
        [Header("Blueprint Reference Settings")]
        [Tooltip("Reference to the town diagram/blueprint texture or data layout generated by Antigravity.")]
        public Texture2D selfGeneratedBlueprintDiagram;
        public float townRadiusWorldUnits = 300f; // Scale matched to Aethelburg Metropolis (300m curtain wall)
        public float centerPeakElevation = 18f;   // Citadel elevation (+18m at Cathedral apex)
        public float minimumStreetClearanceForMounts = 14f;

        [Header("House & Building Prefabs (Kitbashed / Meshy Assets)")]
        public GameObject[] outerRingHousePrefabs;
        public GameObject[] midTierTownhomePrefabs;
        public GameObject[] upperTierResidencePrefabs;
        public GameObject[] bakeryAndShopPrefabs;
        public GameObject[] tentBazaarPrefabs;

        [Header("Runtime & Generation Settings")]
        public bool autoPopulateOnStart = false;
        public bool alignToTerraceSurface = true;
        public LayerMask groundRaycastMask = ~0;

        [Header("Extracted Diagram Plot Ledger")]
        public List<TownBlueprintPlot> diagramPlots = new List<TownBlueprintPlot>();

        private void Start()
        {
            if (Application.isPlaying && autoPopulateOnStart)
            {
                if (transform.childCount == 0)
                {
                    PopulateTownFromOwnDiagram();
                }
            }
        }

