#if UNITY_EDITOR
        private GameObject[] LoadAssetsMatching(params string[] paths)
        {
            List<GameObject> list = new List<GameObject>();
            foreach (var p in paths)
            {
                var go = AssetDatabase.LoadAssetAtPath<GameObject>(p);
                if (go != null) list.Add(go);
            }
            return list.ToArray();
        }
#endif

        [ContextMenu("1. Parse Self-Generated Diagram & Populate Town Houses")]
        public void PopulateTownFromOwnDiagram()
        {
            // Clear prior houses under this transform
            ClearPopulatedHouses();

            AutoAssignBlueprintAssets();

            if (diagramPlots.Count == 0)
            {
                ExtractPlotsFromOwnBlueprintDiagram();
            }

            int instantiatedCount = 0;
            foreach (var plot in diagramPlots)
            {
                Vector3 worldPos = new Vector3(
                    plot.normalizedDiagramCoords.x * townRadiusWorldUnits,
                    plot.elevationHeightY,
                    plot.normalizedDiagramCoords.y * townRadiusWorldUnits
                );

                // If ground raycasting is enabled and hits a surface, snap cleanly
                if (alignToTerraceSurface)
                {
                    Vector3 rayOrigin = new Vector3(worldPos.x, worldPos.y + 10f, worldPos.z);
                    if (Physics.Raycast(rayOrigin, Vector3.down, out RaycastHit hit, 25f, groundRaycastMask))
                    {
                        worldPos.y = hit.point.y;
                    }
                }

                Quaternion rotation = Quaternion.Euler(0f, plot.facingAngleDegrees, 0f);
                GameObject selectedPrefab = SelectPrefabForPlot(plot);

                if (selectedPrefab != null)
                {
#if UNITY_EDITOR
                    GameObject houseInstance = (GameObject)PrefabUtility.InstantiatePrefab(selectedPrefab, this.transform);
                    if (houseInstance == null)
                    {
                        houseInstance = Instantiate(selectedPrefab, worldPos, rotation, this.transform);
                    }
                    else
                    {
                        houseInstance.transform.position = worldPos;
                        houseInstance.transform.rotation = rotation;
                    }
#else
                    GameObject houseInstance = Instantiate(selectedPrefab, worldPos, rotation, this.transform);
#endif
                    houseInstance.transform.localScale = Vector3.one;
                    houseInstance.name = $"TownHouse_{plot.zoneTier}_{plot.plotId}";

                    // Apply materials and collision meshes
                    ApplyStylingAndColliders(houseInstance);

                    instantiatedCount++;
                }
            }

            Debug.Log($"<color=#76FF03><b>[Blueprint Populator] Successfully populated {instantiatedCount} houses, shops, bakeries, and bazaars across 3 concentric rings from Antigravity's blueprint diagram!</b></color>");
        }

        [ContextMenu("2. Clear Populated Town Houses")]
        public void ClearPopulatedHouses()
        {
            var children = new List<GameObject>();
            for (int i = transform.childCount - 1; i >= 0; i--)
            {
                children.Add(transform.GetChild(i).gameObject);
            }

            foreach (var child in children)
            {
#if UNITY_EDITOR
                DestroyImmediate(child);
#else
                Destroy(child);
#endif
            }

            diagramPlots.Clear();
            Debug.Log("[Blueprint Populator] Cleared all previously populated houses.");
        }

        [ContextMenu("1b. Execute San Francisco High-Density Town Packing (0.15m-0.45m Gap)")]
        public void ExecuteSanFranciscoDensePacking()
        {
            var sfPopulator = GetComponent<SanFranciscoDenseTownPopulator>();
            if (sfPopulator == null)
            {
                sfPopulator = gameObject.AddComponent<SanFranciscoDenseTownPopulator>();
            }
            sfPopulator.PopulateHighDensityTown();
        }

        /// <summary>
        /// Reads the concentric tiered rings from Antigravity's circular town diagram.
        /// [DEPRECATED]: Uniform equidistant angular stepping (angleRad = (i / count) * 2PI) is deprecated
        /// in favor of SanFranciscoDenseTownPopulator contiguous zero-lot-line row-house packing.
        /// </summary>
        [Obsolete("Deprecated in favor of SanFranciscoDenseTownPopulator zero-lot-line contiguous packing.")]
        public void ExtractPlotsFromOwnBlueprintDiagram()
        {
            diagramPlots.Clear();

            // Ring 0 (Outer Wall Ring R~0.82 => 246m), Ring 1 (Mid Artisan Tier R~0.55 => 165m), Ring 2 (Upper Sanctuary Ring R~0.30 => 90m)
            float[] ringRadiiNormalized = { 0.82f, 0.55f, 0.30f };
            int[] housesPerRing = { 36, 24, 12 };

            // Standard blueprint elevations corresponding to Metropolis tiers:
            // Outer Ring (Tier 1): 0m - 2m
            // Mid Ring (Tier 2): 6m
            // Upper Ring (Tier 3): 12m
            // Apex Citadel (Tier 4): 18m
            float[] tierElevations = { 0.0f, 6.0f, 12.0f };

            for (int r = 0; r < ringRadiiNormalized.Length; r++)
            {
                float radiusNorm = ringRadiiNormalized[r];
                int count = housesPerRing[r];

                // Elevation increases toward the center Church
                float tierElevation = (r < tierElevations.Length) 
                    ? tierElevations[r] 
                    : Mathf.Lerp(centerPeakElevation, 0f, radiusNorm);

                BlueprintZoneType zone = r == 0 ? BlueprintZoneType.OuterRing_ResidentialAndBazaar :
                                         r == 1 ? BlueprintZoneType.MidRing_TerracedTownhomesAndShops :
                                                  BlueprintZoneType.UpperRing_AcademyAndSanctuaryPerimeter;

                for (int i = 0; i < count; i++)
                {
                    // Deprecated equidistant distribution:
                    float angleRad = (i / (float)count) * Mathf.PI * 2f;

                    // Leave wide radial avenues open at 0, 90, 180, and 270 degrees for mount traffic & mana conduits
                    float angleDeg = angleRad * Mathf.Rad2Deg;
                    if (Mathf.Abs(angleDeg % 90f) < 8f) continue;

                    // In Tier 1 (Outer), also reserve 105-175 degrees for Farmland Agri plots
                    if (r == 0 && angleDeg >= 105f && angleDeg <= 175f) continue;

                    Vector2 normCoords = new Vector2(Mathf.Cos(angleRad) * radiusNorm, Mathf.Sin(angleRad) * radiusNorm);
                    // Orient front door facing the inward/outward street spline
                    float facingCenterRoadAngle = (Mathf.Atan2(-normCoords.x, -normCoords.y) * Mathf.Rad2Deg);

                    // Alternate facing slightly (inward vs outward) for realistic street frontage
                    if (i % 2 == 1) facingCenterRoadAngle += 180f;

                    diagramPlots.Add(new TownBlueprintPlot
                    {
                        plotId = $"R{r}_P{i}",
                        zoneTier = zone,
                        normalizedDiagramCoords = normCoords,
                        elevationHeightY = tierElevation,
                        facingAngleDegrees = facingCenterRoadAngle,
                        isShopOrBakery = (r <= 1 && i % 4 == 0)
                    });
                }
            }
        }

        private GameObject SelectPrefabForPlot(TownBlueprintPlot plot)
        {
            if (plot.isShopOrBakery)
            {
                if (bakeryAndShopPrefabs != null && bakeryAndShopPrefabs.Length > 0)
                {
                    return bakeryAndShopPrefabs[UnityEngine.Random.Range(0, bakeryAndShopPrefabs.Length)];
                }
            }

            if (plot.zoneTier == BlueprintZoneType.OuterRing_ResidentialAndBazaar && (plot.plotId.EndsWith("2") || plot.plotId.EndsWith("6")))
            {
                if (tentBazaarPrefabs != null && tentBazaarPrefabs.Length > 0)
                {
                    return tentBazaarPrefabs[UnityEngine.Random.Range(0, tentBazaarPrefabs.Length)];
                }
            }

            return plot.zoneTier switch
            {
                BlueprintZoneType.OuterRing_ResidentialAndBazaar => GetRandomPrefab(outerRingHousePrefabs),
                BlueprintZoneType.MidRing_TerracedTownhomesAndShops => GetRandomPrefab(midTierTownhomePrefabs),
                BlueprintZoneType.UpperRing_AcademyAndSanctuaryPerimeter => GetRandomPrefab(upperTierResidencePrefabs),
                _ => GetRandomPrefab(outerRingHousePrefabs)
            };
        }

        private GameObject GetRandomPrefab(GameObject[] pool)
        {
            if (pool == null || pool.Length == 0) return null;
            return pool[UnityEngine.Random.Range(0, pool.Length)];
        }

        private void ApplyStylingAndColliders(GameObject go)
        {
            // Call Aethelburg material application if available
            try
            {
                AethelburgMetropolisGenerator.ApplyMetropolisMaterials(go);
            }
            catch
            {
                // Fallback safe if outside editor
            }

            // Ensure corrected meshes and colliders exist on building meshes
            var meshFilters = go.GetComponentsInChildren<MeshFilter>(true);
            foreach (var mf in meshFilters)
            {
#if UNITY_EDITOR
                if (mf.sharedMesh != null && !mf.sharedMesh.name.EndsWith("_Corrected"))
                {
                    string correctedPath = $"Assets/Models/Metropolis/{mf.sharedMesh.name}_Corrected.asset";
                    var corrected = UnityEditor.AssetDatabase.LoadAssetAtPath<Mesh>(correctedPath);
                    if (corrected != null) mf.sharedMesh = corrected;
                }
#endif
                if (mf.sharedMesh != null && mf.GetComponent<Collider>() == null)
                {
                    var col = mf.gameObject.AddComponent<MeshCollider>();
                    col.convex = false;
                }
            }

#if UNITY_EDITOR
            var mrs = go.GetComponentsInChildren<MeshRenderer>(true);
            foreach (var mr in mrs)
            {
                var sharedMats = mr.sharedMaterials;
                bool dirty = false;
                for (int m = 0; m < sharedMats.Length; m++)
                {
                    var mat = sharedMats[m];
                    if (mat == null) continue;
                    string matPath = $"Assets/Materials/Metropolis/{mat.name}.mat";
                    var standAloneMat = UnityEditor.AssetDatabase.LoadAssetAtPath<Material>(matPath);
                    if (standAloneMat != null && standAloneMat != mat)
                    {
                        sharedMats[m] = standAloneMat;
                        mat = standAloneMat;
                        dirty = true;
                    }
                    if (mat.HasProperty("_Cull") && mat.GetFloat("_Cull") != 0f)
                    {
                        mat.SetFloat("_Cull", 0f);
                        mat.doubleSidedGI = true;
                        UnityEditor.EditorUtility.SetDirty(mat);
                    }
                }
                if (dirty) mr.sharedMaterials = sharedMats;
            }
#endif
        }

        private void OnDrawGizmosSelected()
        {
            Gizmos.color = Color.cyan;
            Gizmos.DrawWireSphere(transform.position, townRadiusWorldUnits * 0.82f);
            Gizmos.color = Color.yellow;
            Gizmos.DrawWireSphere(transform.position, townRadiusWorldUnits * 0.55f);
            Gizmos.color = Color.magenta;
            Gizmos.DrawWireSphere(transform.position, townRadiusWorldUnits * 0.30f);

            // Draw clear mount avenue lines (0, 90, 180, 270 degrees)
            Gizmos.color = Color.green;
            Vector3[] avenueDirs = { Vector3.forward, Vector3.back, Vector3.left, Vector3.right };
            foreach (var dir in avenueDirs)
            {
                Gizmos.DrawRay(transform.position, dir * townRadiusWorldUnits);
            }
        }
